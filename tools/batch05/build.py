"""Additive build: existing authored files and the116 canonical chapters stay intact."""
import json,pathlib
R=pathlib.Path(__file__).resolve().parents[2]
allnotes={};register=[];stems=[]
for evidence in sorted((R/'data/batch05').glob('*-sections.json')):
 stem=evidence.name.split('-')[0];prefix=stem[:-2];chapter=int(stem[-2:]);subject={'phys':'物理','chem':'化学','bio':'生物','math':'数学'}[prefix];key=subject+str(chapter)
 base=json.loads((R/'data/base-lessons'/(stem+'.json')).read_text());notes=json.loads((R/'data/notes'/(stem+'.json')).read_text())
 assert [s['id'] for s in base['sections']]==list(notes)
 for sid,u in notes.items():
  assert len(u['examples'])>=3 and len(u['practice'])>=4 and all(u.get(f) for f in ['goals','deep','derive','exam','quick','diagnostics','content_sources'])
  assert sorted(x['goal_index'] for x in u['diagnostics'])==list(range(len(u['goals'])))
 (R/'lessons'/(stem+'.js')).write_text('// Generated by tools/batch05/build.py from curated base data.\nwindow.LESSONS=window.LESSONS||{};\nwindow.LESSONS['+json.dumps(key,ensure_ascii=False)+']='+json.dumps(base,ensure_ascii=False,indent=2)+';\n')
 stems.append(stem);allnotes[key]=notes;register+=json.loads(evidence.read_text())
(R/'lessons/batch05-notes.js').write_text('// Additive authored notes; legacy supplements are preserved.\nObject.assign(window.BATCH_NOTES,'+json.dumps(allnotes,ensure_ascii=False,separators=(',',':'))+');\n')
(R/'data/review/batch05_sections.json').write_text(json.dumps(register,ensure_ascii=False,indent=2)+'\n')
html=R/'index.html';text=html.read_text();import re
for stem in stems:text=text.replace('<script src="lessons/'+stem+'.js"></script>','')
anchor='<script src="lessons/batch05-notes.js"></script>'
text=text.replace(anchor,anchor+''.join('<script src="lessons/'+stem+'.js"></script>' for stem in stems));html.write_text(text)
print('Built',len(stems),'chapters,',len(register),'real sections:',', '.join(stems))
