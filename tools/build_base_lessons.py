"""Compile curated base lessons without reviving superseded Python lesson drafts."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
NAMES={'chem05':'化学5','chem06':'化学6','bio03':'生物3',**{f'chem{i:02}':f'化学{i}' for i in range(7,12)}}
def build(stem):
    key=NAMES[stem]
    obj=json.loads((ROOT/'data/base-lessons'/(stem+'.json')).read_text())
    ids=[s['id'] for s in obj['sections']]
    if len(ids)!=len(set(ids)):raise ValueError('duplicate section IDs')
    text='// Generated by tools/build_base_lessons.py; edit data/base-lessons/'+stem+'.json.\n'
    text+='window.LESSONS=window.LESSONS||{};\nLESSONS['+json.dumps(key,ensure_ascii=False)+']='+json.dumps(obj,ensure_ascii=False,indent=2)+';\n'
    (ROOT/'lessons'/(stem+'.js')).write_text(text)
if __name__=='__main__':
    for stem in NAMES:build(stem)
    print(f'Compiled{len(NAMES)} curated base lessons; subsection identity retained')
