"""Build only reviewed batch06 author files; leave prior lesson bytes unchanged."""
from pathlib import Path
import json,re
R=Path(__file__).resolve().parents[2]
notes={};register=[];stems=[]
for path in sorted((R/'data/batch06').glob('*-sections.json')):
 stem=path.name.split('-')[0]
 base=json.loads((R/f'data/base-lessons/{stem}.json').read_text())
 units=json.loads((R/f'data/notes/{stem}.json').read_text())
 evidence=json.loads(path.read_text())
 assert [(s['id'],s['t']) for s in base['sections']]==[(s['section_id'],s['section_title']) for s in evidence]
 assert list(units)==[s['id'] for s in base['sections']]
 subject=evidence[0]['subject'];chapter=evidence[0]['chapter_id'];key=subject+str(chapter)
 assert all(u['content_batch']=='batch06' for u in units.values())
 # Preserve authentic parent rows in the directory, without counting them as extra lessons.
 source=R/'sources/batch06/official-directory-index.json'
 if source.exists():
  rows=[x for x in json.loads(source.read_text()) if x['subject']==subject and x['chapter_id']==chapter]
  base['directory_groups']=[dict(id=x['section_id'],t=x['section_title'],children=[s['id'] for s in base['sections'] if s['id'].startswith(x['section_id']+'.')]) for x in rows if any(s['id'].startswith(x['section_id']+'.') for s in base['sections'])]
 target=R/f'lessons/{stem}.js'
 if target.exists():assert target.read_text().startswith('// Generated by tools/batch06/'), 'Refusing to overwrite old lesson '+stem
 target.write_text('// Generated by tools/batch06/build.py from independently authored material.\nwindow.LESSONS=window.LESSONS||{};\nwindow.LESSONS['+json.dumps(key,ensure_ascii=False)+']='+json.dumps(base,ensure_ascii=False,indent=2)+';\n')
 notes[key]=units;register+=evidence;stems.append(stem)
(R/'lessons/batch06-notes.js').write_text('// Additive batch06; original supplements are untouched.\nObject.assign(window.BATCH_NOTES,'+json.dumps(notes,ensure_ascii=False,separators=(',',':'))+');\n')
(R/'data/review/batch06_sections.json').write_text(json.dumps(register,ensure_ascii=False,indent=2)+'\n')
html=R/'index.html';text=html.read_text()
for stem in stems+['batch06-notes']:text=text.replace('<script src="lessons/'+stem+'.js"></script>','')
tag=''.join('<script src="lessons/'+stem+'.js"></script>' for stem in stems+['batch06-notes'])
anchor='<script src="batch-ui.js"></script>';assert text.count(anchor)==1
html.write_text(text.replace(anchor,tag+anchor))
print('Built',len(stems),'new canonical chapters and',len(register),'real sections')

formulas=json.loads((R/'data/batch06/formulas.json').read_text())
(R/'lessons/batch06-formulas.js').write_text('// Additive verified batch06 formula cards; original cards remain unchanged.\nObject.assign(window.STUDY_FORMULAS,'+json.dumps(formulas,ensure_ascii=False,indent=2)+');\n')
text=html.read_text();tag='<script src="lessons/batch06-formulas.js"></script>'
text=text.replace(tag,'');anchor='<script src="data/formula-cards.js"></script>';assert text.count(anchor)==1
html.write_text(text.replace(anchor,anchor+tag))
